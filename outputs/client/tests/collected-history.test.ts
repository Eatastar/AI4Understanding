import assert from 'node:assert/strict';
import test from 'node:test';
import { collectHistory, collectionChoices } from '../src/domain/collected-history';
import { buildProjectChatContext, createProject, createProjectChat } from '../src/domain/projects';
import { createAnnotation, createAssistantMessage, createConversation, createUserMessage, saveNoteAnnotation, validateImport } from '../src/domain/workspace';
import { unpackWorkspace, WorkspaceCodec } from '../src/domain/workspace-codec';
import type { Workspace } from '../src/domain/types';

test('collection keeps the selected rounds in original time order and requires explicit context opt-in', () => {
  const project = createProject('A project');
  project.documents = [{ id: 'file', name: 'Test.pdf', kind: 'pdf', mimeType: 'application/pdf', size: 20, createdAt: 1, pages: [{ messageId: 'page', versionId: 'pv', text: 'PDF MATERIAL', pageNumber: 1 }] }];
  const note = createAnnotation(project, { mode: 'note', messageId: 'page', versionId: 'pv', quote: 'PDF', anchor: {}, color: '#654321' });
  project.annotations = saveNoteAnnotation({ ...project, annotations: [note] }, note.id, 'Project note').annotations;
  const early = createUserMessage('First selected question'), later = createUserMessage('Later selected question');
  early.versions[0].createdAt = 1;
  later.versions[0].createdAt = 2;
  const reference = { annotationId: note.id, label: 'Test.pdf', quote: 'PDF', question: '', answer: '', mode: 'note' as const, note: 'Project note' };
  early.annotationReferences = [reference]; later.annotationReferences = [reference];
  const first = { ...createConversation('First'), projectId: project.id, messages: [early, createAssistantMessage('First answer', 'complete'), createUserMessage('Unrelated follow-up')] };
  const second = { ...createConversation('Second'), projectId: project.id, messages: [later, createAssistantMessage('Later answer', 'complete')] };
  const unrelated = { ...createConversation('Other'), messages: [{ ...createUserMessage('Outside project'), annotationReferences: [reference] }] };
  const space: Workspace = { schemaVersion: 1, activeConversationId: first.id, conversations: [project, second, unrelated, first] };
  const choices = collectionChoices(space, project.id, note);
  assert.deepEqual(choices.filter(choice => choice.related).map(choice => choice.id), [early.id, later.id]);
  assert.equal(choices.some(choice => choice.preview === 'Outside project'), false);
  const turns = collectHistory(space, project.id, note, [later.id, early.id]);
  assert.deepEqual(turns.map(turn => turn.question), ['First selected question', 'Later selected question']);
  const question = createUserMessage('My next question');
  const current = { ...createConversation('Collected'), messages: [question], collectedHistory: { annotationId: note.id, turns } };
  const next = createProjectChat(space, project.id, current);
  const chat = next.conversations[0];
  const content = () => buildProjectChatContext(next, chat, '').map(message => message.content).join('\n');
  assert.doesNotMatch(content(), /First answer|PDF MATERIAL/);
  question.useCollectedHistory = true;
  assert.match(content(), /First answer/);
  assert.doesNotMatch(content(), /PDF MATERIAL|Unrelated follow-up/);
  const packed = new WorkspaceCodec().pack(next);
  assert.deepEqual(validateImport(unpackWorkspace({ ...packed.header, records: packed.rows })).conversations[0].collectedHistory, current.collectedHistory);
});
